@bot.message_handler(commands=['choice'])
def choice(message):
    try:
        # Получаем текст после команды /choice
        text = message.text.replace('/choice', '').strip()

        if not text:
            bot.send_message(message.chat.id,
                             'Пожалуйста, укажите варианты через запятую.\nПример: /choice пицца, суши, бургер')
            return

        # Разделяем варианты по запятой
        options = [opt.strip() for opt in text.split(',') if opt.strip()]

        if len(options) < 2:
            bot.send_message(message.chat.id,
                             'Нужно указать как минимум 2 варианта для выбора.\nПример: /choice пицца, суши, бургер')
            return

        # Выбираем случайный вариант
        chosen = random.choice(options)

        # Формируем ответ
        response = f"📋 *Варианты:* {', '.join(options)}\n"
        response += f"🎯 *Мой выбор:* **{chosen}**"

        bot.send_message(message.chat.id, response, parse_mode='Markdown')

    except Exception as e:
        bot.send_message(message.chat.id,
                         f'Произошла ошибка: {str(e)}\nПожалуйста, используйте формат: /choice вариант1, вариант2, вариант3')


