@bot.message_handler(content_types=['text'])
def handle_text(message):
    text = message.text.lower().strip()

    # Приветствие
    if text == 'привет' or text == 'приветик' or text == 'здравствуй':
        bot.send_message(message.chat.id, 'Пппппппппрррррррррииииииииввввввввееееееееттттттт')

    # Триггер на слово "скучно"
    elif any(word in text for word in ['скучно', 'скучаю', 'грустно', 'нечем заняться', 'мне скучно']):
        bot.send_message(message.chat.id, 'О, я знаю, как развеселиться! ✨')
        time.sleep(0.5)
        suggest_activity(message)

    # Обработка выбора жанра фильма
    elif text in ['1', '2', '3', '4', '5', '6', '7']:
        genre_map = {
            '1': 'комедия',
            '2': 'драма',
            '3': 'фантастика',
            '4': 'боевик',
            '5': 'ужасы',
            '6': 'аниме',
            '7': 'мелодрама'
        }
        genre = genre_map[text]
        recommend_film(message, genre)

    # Обработка названий жанров
    elif any(genre in text for genre in ['комедия', 'драма', 'фантастика', 'боевик', 'ужасы', 'аниме', 'мелодрама']):
        for genre in films_by_genre.keys():
            if genre in text:
                recommend_film(message, genre)
                break

    # Помощь по команде /film
    elif 'фильм' in text and 'что' in text:
        film_menu(message)


